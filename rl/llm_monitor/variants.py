"""Config variants: configs/countdown_code_hack.yaml with only the monitor
(`rh_detector`) swapped. Reward, ground-truth channels and eval metrics are
byte-identical to the paper's config, so arms differ in the monitor alone.

The YAML files are generated (and checked in) rather than hand-copied:
    python -m llm_monitor.variants
"""
from __future__ import annotations

import os
import re

BASE = "configs/countdown_code_hack.yaml"

MONITORS = {
    # upper bound: ground truth over all hack forms
    "oracle": """rh_detector:
  name: score_threshold
  component: countdown_hack_from_all
  params:
    threshold: 0.5
""",
    # LLM judge, hard flag at the frozen threshold
    "judge": """rh_detector:
  name: llm_judge_countdown
  params: {}
""",
    # LLM judge, confidence-weighted routing
    "judge_soft": """rh_detector:
  name: llm_judge_countdown
  params:
    soft: true
""",
}

_BLOCK = re.compile(r"^rh_detector:\n(?:[ \t]+.*\n)+", re.MULTILINE)


def variant_path(name):
    return f"configs/llmmon_countdown_{name}.yaml"


def write_all(root="."):
    text = open(os.path.join(root, BASE)).read()
    assert len(_BLOCK.findall(text)) == 1, "expected exactly one rh_detector block"
    for name, block in MONITORS.items():
        header = (f"# GENERATED by llm_monitor/variants.py from {BASE}: only rh_detector differs.\n"
                  f"# Monitor variant: {name}\n")
        with open(os.path.join(root, variant_path(name)), "w") as f:
            f.write(header + _BLOCK.sub(lambda _: block, text))


if __name__ == "__main__":
    write_all()
    print("wrote", [variant_path(n) for n in MONITORS])
